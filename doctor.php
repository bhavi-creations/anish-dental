<script>
function toggleDoctorDetails(button) {

    const expertiseBox = button.closest('.expertise-box');
    const moreContent = expertiseBox.querySelector('.doctor-more-content');

    const label = button.querySelector('span');
    const arrow = button.querySelector('i');

    if (moreContent.classList.contains('show')) {

        moreContent.classList.remove('show');

        label.textContent = 'VIEW PROFILE';

        arrow.className = 'fa-solid fa-arrow-right';

    } else {

        moreContent.classList.add('show');

        label.textContent = 'CLOSE PROFILE';

        arrow.className = 'fa-solid fa-arrow-up';

    }
}
</script>




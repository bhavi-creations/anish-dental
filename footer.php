document.addEventListener("DOMContentLoaded", function () {

    const logoWrappers = document.querySelectorAll(".anish_reusable_logo");

    logoWrappers.forEach(function (wrapper) {

        const image = wrapper.querySelector(".anish_reusable_logo_source");
        const canvas = wrapper.querySelector(".anish_reusable_logo_canvas");

        if (!image || !canvas) return;


        function recolorLogo() {

            const ctx = canvas.getContext("2d", {
                willReadFrequently: true
            });

            canvas.width = image.naturalWidth;
            canvas.height = image.naturalHeight;

            ctx.clearRect(
                0,
                0,
                canvas.width,
                canvas.height
            );

            ctx.drawImage(
                image,
                0,
                0
            );


            const imageData = ctx.getImageData(
                0,
                0,
                canvas.width,
                canvas.height
            );

            const pixels = imageData.data;


            for (let i = 0; i < pixels.length; i += 4) {

                const r = pixels[i];
                const g = pixels[i + 1];
                const b = pixels[i + 2];
                const a = pixels[i + 3];

                if (a === 0) continue;


                /*
                    Detect green / teal areas only.

                    Green tooth outline
                    Green ANISH DENTAL text
                    Green subtitle

                    → converted to WHITE

                    Gold portions remain unchanged.
                */
                const isGreenTeal =
                    g > r + 14 &&
                    g >= b * 0.82 &&
                    r < 150 &&
                    g < 190;


                if (isGreenTeal) {

                    pixels[i]     = 255;
                    pixels[i + 1] = 255;
                    pixels[i + 2] = 255;
                    pixels[i + 3] = a;

                }

            }


            ctx.putImageData(
                imageData,
                0,
                0
            );
        }


        if (
            image.complete &&
            image.naturalWidth > 0
        ) {

            recolorLogo();

        } else {

            image.addEventListener(
                "load",
                recolorLogo
            );

        }

    });

});
</script>

<script>
document.addEventListener("DOMContentLoaded", function () {

    const image  = document.getElementById("contactusLogoSource");
    const canvas = document.getElementById("contactusLogoCanvas");

    if (!image || !canvas) return;

    function recolorLogo() {

        const ctx = canvas.getContext("2d", {
            willReadFrequently: true
        });

        canvas.width  = image.naturalWidth;
        canvas.height = image.naturalHeight;

        ctx.clearRect(0, 0, canvas.width, canvas.height);
        ctx.drawImage(image, 0, 0);

        const imageData = ctx.getImageData(
            0,
            0,
            canvas.width,
            canvas.height
        );

        const pixels = imageData.data;

        for (let i = 0; i < pixels.length; i += 4) {

            const r = pixels[i];
            const g = pixels[i + 1];
            const b = pixels[i + 2];
            const a = pixels[i + 3];

            if (a === 0) continue;

            /*
               Detect dark green / teal logo portions only.

               Gold remains untouched because gold has:
               red > green.

               Green/teal has:
               green > red and blue close to green.
            */
            const isGreenTeal =
                g > r + 14 &&
                g >= b * 0.82 &&
                r < 150 &&
                g < 190;

            if (isGreenTeal) {

                pixels[i]     = 255; /* Red   */
                pixels[i + 1] = 255; /* Green */
                pixels[i + 2] = 255; /* Blue  */

                /* Keep original transparency */
                pixels[i + 3] = a;
            }
        }

        ctx.putImageData(imageData, 0, 0);
    }


    if (image.complete && image.naturalWidth > 0) {
        recolorLogo();
    } else {
        image.addEventListener("load", recolorLogo);
    }

});
</script>
